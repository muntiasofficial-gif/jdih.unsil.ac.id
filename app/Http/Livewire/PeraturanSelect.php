<?php

namespace App\Http\Livewire;

use App\Attributes\AttributeLivewireSelect;
use App\Models\Kategori;
use App\Models\Peraturan;
use Asantibanez\LivewireSelect\LivewireSelect;
use Illuminate\Support\Collection;
use Livewire\Component;

class PeraturanSelect extends LivewireSelect
{
    public $peraturan_id = false;
    public $selected_id = false;
    use AttributeLivewireSelect;

    public function mount($name, $value = null, $placeholder = 'Select an option', $searchable = false, $dependsOn = [], $dependsOnValues = [], $waitForDependenciesToShow = false, $noResultsMessage = 'No options found', $selectView = 'livewire-select::select', $defaultView = 'livewire-select::default', $searchView = 'livewire-select::search', $searchInputView = 'livewire-select::search-input', $searchOptionsContainer = 'livewire-select::search-options-container', $searchOptionItem = 'livewire-select::search-option-item', $searchSelectedOptionView = 'livewire-select::search-selected-option', $searchNoResultsView = 'livewire-select::search-no-results', $extras = [])
    {
        if ($this->selected_id) {
            $this->selectValue($this->selected_id);
        }
        return parent::mount($name, $value, $placeholder, $searchable, $dependsOn, $dependsOnValues, $waitForDependenciesToShow, $noResultsMessage, $selectView, $defaultView, $searchView, $searchInputView, $searchOptionsContainer, $searchOptionItem, $searchSelectedOptionView, $searchNoResultsView, $extras); // TODO: Change the autogenerated stub
    }

    public function selectValue($value)
    {
        $this->emit("peraturan_select", $value);
        parent::selectValue($value);
    }

    public function options($searchTerm = null): Collection
    {

        $data = Peraturan::when($searchTerm, function ($q) use ($searchTerm) {
            $q->where('judul', 'like', '%' . $searchTerm . '%');
        })
            ->when($this->peraturan_id, function ($q) {
                $q->where('id', '!=', $this->peraturan_id);
            })
            ->get();
        foreach ($data as $item) {
            $temp[] = [
                'value' => $item->id,
                'description' => $item->judul
            ];
        }
        return collect(@$temp ?? []);
    }

    public function selectedOption($value)
    {
        $kategori = Peraturan::findOrFail($value);
        $this->emit("peraturan_select", $value);
        return [
            'value' => $kategori->id,
            'description' => $kategori->judul,
        ];
    }
}
